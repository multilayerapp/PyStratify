"""Point dipoles beside a sphere against smuthi (benchmarks/MATRIX.md, spheres).

    python benchmarks/smuthi_spheres.py         # prints SMUTHI_SPHERES.md (~8 min, one core); needs smuthi

smuthi (Egel et al., JQSRT 273, 107846 (2021)) couples a dipole to a particle through the particle's T-matrix
(Mie, for a sphere) and its own translation of the dipole's field into spherical waves about the particle;
the dissipated power then comes from the field scattered back at the dipole. Nothing is shared with
PyStratify's recursive transfer matrices and closed-form decay rates, so agreement to many digits checks
the formulation, not only the numerics. smuthi's truncation l_max converges geometrically; the report
shows it for each case. smuthi builds only on Python <= 3.10 with NumPy < 2 (see emitter_references.py);
it places a dipole outside particles only, and supports electric dipoles, so magnetic and interior
sources stay with the 60-digit reference (MATRIX.md).

Cases (lengths in nm, a host medium on both sides of smuthi's single interface):

* a dielectric sphere, n = 2, R = 150 nm, dipole 100 nm away, 800 nm;
* a metal-like sphere, eps = -10 + i, R = 20 nm, dipole 5 nm away, 600 nm (the near field: high orders);
* a sphere in water, n = 1.5, R = 100 nm, dipole 20 nm away, 633 nm;
* a large high-index sphere, n = 3.5 + 0.01i, R = 500 nm, dipole 50 nm away, 800 nm.
"""

from __future__ import annotations

import contextlib
import io
import sys
import time
import warnings
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pystratify as ps  # noqa: E402

# name -> (wavelength, sphere radius, sphere index, host index, gap from the surface, smuthi l_max ladder)
CASES = {
    "dielectric, n = 2, R = 150 nm, 100 nm away": (800.0, 150.0, 2.0, 1.0, 100.0, (6, 10)),
    "metal-like, eps = -10 + i, R = 20 nm, 5 nm away": (600.0, 20.0, np.sqrt(-10 + 1j + 0j), 1.0, 5.0, (20, 40, 60)),
    "in water, n = 1.5, R = 100 nm, 20 nm away": (633.0, 100.0, 1.5, 1.33, 20.0, (10, 20)),
    "large high-index, n = 3.5 + 0.01i, R = 500 nm, 50 nm away": (800.0, 500.0, 3.5 + 0.01j, 1.0, 50.0, (20, 40, 60)),
}
ORIENTATIONS = ("radial", "tangential")


def stratify(case):
    wavelength, radius, n, host, gap, _ = CASES[case]
    problem = ps.Problem("spheres", [radius / 1000], [n, host], wavelength / 1000,
                         ps.PointDipole((radius + gap) / 1000, "electric", 1), 1e-10)
    return np.asarray(ps.solve_problem(problem)["total"][:2])


def smuthi_rates(case, l_max):
    """smuthi's (radial, tangential) total rates relative to the dipole in the host."""
    stdout = sys.stdout
    with contextlib.redirect_stdout(io.StringIO()):
        import smuthi.initial_field as initial
        import smuthi.layers as layers
        import smuthi.particles as particles
        import smuthi.simulation as simulation
    sys.stdout = stdout  # importing smuthi replaces the stream it was given
    wavelength, radius, n, host, gap, _ = CASES[case]
    system = layers.LayerSystem(thicknesses=[0, 0], refractive_indices=[host, host])
    rates = []
    for moment in ([0, 0, 1], [1, 0, 0]):  # along and across the line through the sphere's centre
        sphere = particles.Sphere(position=[0, 0, 0], refractive_index=n, radius=radius, l_max=l_max)
        source = initial.DipoleSource(vacuum_wavelength=wavelength, dipole_moment=moment, position=[0, 0, radius + gap])
        with contextlib.redirect_stdout(io.StringIO()), warnings.catch_warnings():
            warnings.simplefilter("ignore")
            simulation.Simulation(layer_system=system, particle_list=[sphere], initial_field=source,
                                  log_to_terminal=False).run()
            power = float(np.squeeze(source.dissipated_power([sphere], system, show_progress=False)))
            free = float(np.squeeze(source.dissipated_power_homogeneous_background(system)))
        rates.append(power / free)
    return np.array(rates)


def compare(cases=tuple(CASES), ladders=None):
    """{case: (PyStratify rates, [(l_max, smuthi rates, seconds)])}."""
    out = {}
    for case in cases:
        runs = []
        for l_max in (ladders or {}).get(case, CASES[case][-1]):
            start = time.time()
            runs.append((l_max, smuthi_rates(case, l_max), time.time() - start))
        out[case] = stratify(case), runs
    return out


def report(results):
    print("# Dipoles beside a sphere: PyStratify against smuthi\n")
    print("Generated by `python benchmarks/smuthi_spheres.py` (smuthi 2.2.4, Mie T-matrix and its own translation")
    print("of the dipole field). Total decay rate relative to the dipole in the host, electric dipole along (radial)")
    print("and across (tangential) the line through the sphere's centre; max |smuthi / PyStratify - 1| per smuthi")
    print("truncation l_max (PyStratify at tolerance 1e-10).\n")
    print("| case | PyStratify radial | PyStratify tangential | smuthi l_max: difference (time) |")
    print("|---|---|---|---|")
    for case, (exact, runs) in results.items():
        cells = ", ".join(f"{l_max}: {np.max(np.abs(rates / exact - 1)):.1e} ({seconds:.0f} s)" for l_max, rates, seconds in runs)
        print(f"| {case} | {exact[0]:.9f} | {exact[1]:.9f} | {cells} |")


if __name__ == "__main__":
    report(compare())
